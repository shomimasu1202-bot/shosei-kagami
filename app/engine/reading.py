@dataclass(frozen=True)
class SectionReading:
    """1 セクション分の鑑定文。JSON シリアライズ可能。"""

    section_id: str
    title: str
    text: str

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass(frozen=True)
class Reading:
    """タイプの鑑定文一式。JSON シリアライズ可能。"""

    type_id: str
    名称: str
    読み: str
    五行: str
    陰陽: str
    headline: str
    sections: tuple[SectionReading, ...]

    def to_dict(self) -> dict:
        return {
            "type_id": self.type_id,
            "名称": self.名称,
            "読み": self.読み,
            "五行": self.五行,
            "陰陽": self.陰陽,
            "headline": self.headline,
            "sections": [s.to_dict() for s in self.sections],
        }


def _compose_section(t: ShoseiType, section_id: str) -> str:
    """3層（タイプ→五行→陰陽）を連結して1段落にする。"""
    parts = [
        TYPE_TEXT[t.type_id][section_id],
        ELEMENT_FLAVOR[t.五行][section_id],
        YINYANG_FLAVOR[t.陰陽][section_id],
    ]
    return "".join(parts)


def build_reading_for_type(t: ShoseiType) -> Reading:
    """ShoseiType から鑑定文を組み立てる（決定的）。"""
    headline = f"{t.名称}（{t.読み}）― {t.一言特徴}【五行:{t.五行}／{t.陰陽}】"
    sections = tuple(
        SectionReading(
            section_id=sid,
            title=title,
            text=_compose_section(t, sid),
        )
        for sid, title in SECTIONS
    )
    return Reading(
        type_id=t.type_id,
        名称=t.名称,
        読み=t.読み,
        五行=t.五行,
        陰陽=t.陰陽,
        headline=headline,
        sections=sections,
    )


def get_reading(
    value: _dt.date | _dt.datetime,
    *,
    late_night_boundary: bool = False,
) -> Reading:
    """生年月日 → 鑑定文（日干タイプ＋五行陰陽で合成）。"""
    t = get_type(value, late_night_boundary=late_night_boundary)
    return build_reading_for_type(t)
